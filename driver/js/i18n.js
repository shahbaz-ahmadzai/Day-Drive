let lang = "de";
export function setLang(l) {
  lang = T[l] ? l : "de";
  try { localStorage.setItem("dd-driver-lang", lang); } catch (_) {}
  document.documentElement.lang = lang;
  document.documentElement.dir = RTL.includes(lang) ? "rtl" : "ltr";
  return lang;
}
export function savedLang() {
  try { const s = localStorage.getItem("dd-driver-lang"); if (T[s]) return s; } catch (_) {}
  const n = (navigator.language || "de").slice(0, 2).toLowerCase();
  return T[n] ? n : "de";
}
export const getLang = () => lang;
export function t(key, vars) {
  let s = T[lang]?.[key] ?? T.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
  return s;
}
